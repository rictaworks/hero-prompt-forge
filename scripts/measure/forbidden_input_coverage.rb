# 禁止入力の検出範囲を、両方向で測ります（requirements.md 4.1 の 1）。
#
# **片方だけを追うと、検出側が痩せても気づけません。**
# 素材の一覧は、レビューで積み上げたものです。減らさずに足してください。
class ForbiddenInputCoverage
  # 止めるべき言い回しです。
  def blocked
    [
      '他社のロゴは画面の中央に配置してください。',
      '他社のロゴ画像を背景に載せてください。',
      '他社のロゴだけをそのまま使用します。',
      '競合のロゴなどを並べて配置してください。',
      '他社のロゴを、画面の右下の目立つ位置に小さく配置してください。',
      '他社のロゴを大きく掲載してください。',
      '他社事務所のロゴと並べた構図にします。',
      '競合他社の商標を背景に入れてください。',
      '取引先のエンブレムをそのまま使います。',
      'Apple のロゴを中央に配置してください。',
      'スターバックスのロゴを看板に入れてください。',
      'ジブリ風の背景にしてください。',
      '大谷翔平さんの写真を使います。',
      # **「ずみ」を打ち消しとして拾わないことを確かめます**（issue #148）。
      '他社のロゴは掲載ずみの資料と同じ位置に置いてください。',
      '他社のロゴを配置ずみのレイアウトへそのまま入れてください。',
      # **読点の先の語まで打ち消しとして拾わないことを確かめます。**
      '他社のロゴを大きく載せ、装飾は不要です。',
      '他社のロゴを中央に置き、余白は控えめにします。',
      # **別の対象に掛かる語を、打ち消しとして拾わないことを確かめます**
      # （PR #157 のレビューより）。助詞が「を」「に」でも守れることを見ます。
      '他社のロゴを大きく載せて加工を控えめにしてください。',
      '他社のロゴを中央に配置して余白を不要なほど詰めます。',
      '他社のロゴをそのまま使い色数は控えめにします。',
      '他社のロゴを載せてほしいのですが不可能でしょうか。',
      '他社のロゴを大きく載せ、加工を控えめにしてください。',
      '他社のロゴを中央に配置し、余白を控えめに取ってください。',
      '他社のロゴを載せてください、遠慮はいりません。',
      '他社のロゴを大きく載せてください、装飾を控えめに。',
      '他社のロゴをそのまま使い、色だけを控えめにします。',
      '他社のロゴを配置し、文字を不要なほど小さくします。',
      # **「そのまま」に動詞が続かない書き方も、流用の依頼です**
      # （PR #157 の 2 回目のレビューより）。
      '他社のロゴをそのままにしてください。',
      '他社のロゴをそのままお願いします。',
      '他社のロゴをそのままでお願いします。',
      # **依頼の言い回しを、打ち消しとして拾いません。**
      '他社のロゴを入れてくださいませんか。',
      '他社のロゴを載せていただけませんか。',
      '他社のロゴを載せてもかまいませんか。',
      '他社のロゴを載せてほしいのですが不要でしょうか。',
      '他社のロゴをのせてもらえませんでしょうか。',
      # **別の対象に掛かる「不要な◯◯」を、打ち消しとして拾いません。**
      '他社のロゴを大きく載せて不要な装飾を省きます。',
      '他社のロゴを配置して不要な余白を詰めます。'
    ]
  end

  # 通すべき言い回しです。
  #
  # **権利に配慮したお客さまの文を止めてはいけません。**
  # 打ち消しの文（「他社のロゴは使用しません」）は、止めるべき文と正反対の
  # 内容です（PR #144 のレビューより）。
  def passed
    ordinary + negations
  end

  def ordinary
    [
      '他社のロゴの調査結果を掲載します。',
      '他社の商標を侵害しないか確認します。',
      'ロゴ制作を承っております。',
      '当事務所のロゴを中央に配置してください。',
      'ブランドのロゴを大きく見せたいです。',
      'オーナー様のこだわりをお伝えします。',
      '担当者様が丁寧に対応します。',
      '代表取締役社長のあいさつを載せます。',
      '税理士がお応えします。',
      '実在する当院の外観写真を使います。',
      '他社のロゴが入った看板を背景に使います。',
      '商標登録の出願を代行します。',
      'デザイナーが伴走します。',
      'ロゴマークの刷新をご提案します。',
      '看板のデザインを一新します。'
    ]
  end

  # 打ち消しの文です。**権利に配慮した内容ですので、止めません。**
  def negations
    [
      '他社のロゴは使用しません。',
      '他社の商標は掲載しておりません。',
      '競合のロゴは載せないでください。',
      '他社のロゴは配置しないでください。',
      '他社のロゴは、当社の制作物には入れません。',
      '他社のロゴは著作権法上そのまま使えません。',
      '他社のロゴは使いません。',
      '他社のロゴを使用しません。',
      '他社のロゴを載せないでください。',
      '他社のロゴは使用禁止です。',
      # **丁寧な言い回しも打ち消しです**（issue #148）。
      # B2B の商用文では、この形のほうが多く使われます。
      '他社のロゴは載せることができません。',
      '他社のロゴは掲載を控えております。',
      '他社のロゴは配置いたしかねます。',
      '他社の商標は使用を避けております。',
      '他社のロゴの掲載はご遠慮いただいております。',
      '他社のロゴを載せることは、いたしかねます。',
      # **漢字を挟む丁寧な打ち消しです**（PR #157 の 2 回目のレビューより）。
      '他社のロゴを載せる予定はございません。',
      '他社のロゴは掲載を差し控えております。',
      '他社のロゴを使うことは差し控えたいと考えております。',
      '他社のロゴを使用することは、契約上できません。',
      '他社のロゴを掲載する行為は禁止されています。',
      '他社のロゴを使用することは著作権法上できません。',
      '他社のロゴを載せることは、社内規程で禁止しております。'
    ]
  end

  def report
    detector = Generation::ForbiddenDetector.new
    missed = blocked.reject { |text| detector.call(service_summary: text).forbidden? }
    false_positive = passed.select { |text| detector.call(service_summary: text).forbidden? }

    puts "止めるべき #{blocked.size} 件 : 取りこぼし #{missed.size} 件"
    missed.each { |text| puts "  取りこぼし: #{text}" }
    puts "通すべき #{passed.size} 件 : 誤検出 #{false_positive.size} 件"
    false_positive.each { |text| puts "  誤検出: #{text}" }
  end
end

ForbiddenInputCoverage.new.report
