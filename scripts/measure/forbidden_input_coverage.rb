# 禁止入力の検出範囲を、両方向で測ります（requirements.md 4.1 の 1）。
#
# **片方だけを追うと、検出側が痩せても気づけません。**
# 素材の一覧は、レビューで積み上げたものです。減らさずに足してください。
class ForbiddenInputCoverage
  # 止めるべき言い回しです。
  def blocked
    [
      '他社のロゴは画面の中央に配置してください。',
      '他社のロゴ画像を背景に載せてください。',
      '他社のロゴだけをそのまま使用します。',
      '競合のロゴなどを並べて配置してください。',
      '他社のロゴを、画面の右下の目立つ位置に小さく配置してください。',
      '他社のロゴを大きく掲載してください。',
      '他社事務所のロゴと並べた構図にします。',
      '競合他社の商標を背景に入れてください。',
      '取引先のエンブレムをそのまま使います。',
      'Apple のロゴを中央に配置してください。',
      'スターバックスのロゴを看板に入れてください。',
      'ジブリ風の背景にしてください。',
      '大谷翔平さんの写真を使います。'
    ]
  end

  # 通すべき言い回しです。
  #
  # **権利に配慮したお客さまの文を止めてはいけません。**
  # 打ち消しの文（「他社のロゴは使用しません」）は、止めるべき文と正反対の
  # 内容です（PR #144 のレビューより）。
  def passed
    ordinary + negations
  end

  def ordinary
    [
      '他社のロゴの調査結果を掲載します。',
      '他社の商標を侵害しないか確認します。',
      'ロゴ制作を承っております。',
      '当事務所のロゴを中央に配置してください。',
      'ブランドのロゴを大きく見せたいです。',
      'オーナー様のこだわりをお伝えします。',
      '担当者様が丁寧に対応します。',
      '代表取締役社長のあいさつを載せます。',
      '税理士がお応えします。',
      '実在する当院の外観写真を使います。',
      '他社のロゴが入った看板を背景に使います。',
      '商標登録の出願を代行します。',
      'デザイナーが伴走します。',
      'ロゴマークの刷新をご提案します。',
      '看板のデザインを一新します。'
    ]
  end

  # 打ち消しの文です。**権利に配慮した内容ですので、止めません。**
  def negations
    [
      '他社のロゴは使用しません。',
      '他社の商標は掲載しておりません。',
      '競合のロゴは載せないでください。',
      '他社のロゴは配置しないでください。',
      '他社のロゴは、当社の制作物には入れません。',
      '他社のロゴは著作権法上そのまま使えません。',
      '他社のロゴは使いません。',
      '他社のロゴを使用しません。',
      '他社のロゴを載せないでください。',
      '他社のロゴは使用禁止です。'
    ]
  end

  def report
    detector = Generation::ForbiddenDetector.new
    missed = blocked.reject { |text| detector.call(service_summary: text).forbidden? }
    false_positive = passed.select { |text| detector.call(service_summary: text).forbidden? }

    puts "止めるべき #{blocked.size} 件 : 取りこぼし #{missed.size} 件"
    missed.each { |text| puts "  取りこぼし: #{text}" }
    puts "通すべき #{passed.size} 件 : 誤検出 #{false_positive.size} 件"
    false_positive.each { |text| puts "  誤検出: #{text}" }
  end
end

ForbiddenInputCoverage.new.report
